#!/usr/bin/env bash
# Deep sensitive-evidence scan: check-sensitive-evidence.sh cannot see inside
# zip archives (Playwright traces, report bundles). This helper unpacks every
# zip under the evidence tree into a scratch directory and scans the unpacked
# tree together with the original tree (acceptance plan 2026-09-19, item 2.7).
#
#   bash scripts/check-sensitive-evidence-deep.sh EVIDENCE_DIR SECRET_FILE...
#
# SECRET_FILE IS REQUIRED, NOT OPTIONAL. The deep scan is only meaningful with
# the .env-derived value set produced by
# scripts/collect-evidence-secret-values.sh:
#
#   SECRET_SET="$(mktemp)"
#   bash scripts/collect-evidence-secret-values.sh .env "$SECRET_SET"
#   bash scripts/check-sensitive-evidence-deep.sh <evidence-dir> "$SECRET_SET"
#   rm -f "$SECRET_SET"
#
# A call without at least one readable SECRET_FILE, or with a set whose lines
# are all empty, is refused with exit 2: unpacking archives to search for
# nothing produces a "clean" verdict that proves nothing.
#
# Hits are listed per file and per line — `<archive>!<member>:<line>` for a hit
# inside an archive, `<path>:<line>` for a loose file — with the value length
# and a first/last-character mask. The value text is never printed.
#
# Exit codes:
#   0  clean - loose files and every zip archive were scanned, no secret found
#   1  hit - a secret value was found (inside an archive or in loose files)
#   2  usage or setup error - missing/empty secret-value set or evidence
#      directory; the scan did not run
#   3  at least one archive could not be unpacked, or the scan of an unpacked
#      archive failed; the failing archives are listed on stderr. An unpack
#      failure is never read as a clean scan.
# The scratch copy is always removed by the EXIT trap; no archive is modified
# in place.
set -Eeuo pipefail
cd "$(dirname "$0")/.."

usage() {
  echo "usage: bash scripts/check-sensitive-evidence-deep.sh EVIDENCE_DIR SECRET_FILE..." >&2
  echo "  EVIDENCE_DIR  tree to unpack and scan (zip archives included)" >&2
  echo "  SECRET_FILE   REQUIRED: one literal secret value per line, generated by" >&2
  echo "                scripts/collect-evidence-secret-values.sh" >&2
}

if [[ "${1:-}" == "-h" || "${1:-}" == "--help" ]]; then
  usage
  exit 0
fi

if (( $# < 2 )); then
  echo "deep scan refused: no secret-value set given (this scan must be driven by the .env-derived value set)" >&2
  usage
  exit 2
fi

evidence="$1"
shift
if ! test -d "$evidence"; then
  echo "evidence directory is missing or not a directory: $evidence" >&2
  exit 2
fi

work="$(mktemp -d "${TMPDIR:-/tmp}/check-sensitive-evidence-deep.XXXXXX")"
trap 'rm -rf -- "$work"' EXIT

# Validate the value set before unpacking anything.
patterns="$work/patterns"
: > "$patterns"
for secret_file in "$@"; do
  if ! test -r "$secret_file"; then
    echo "secret file is missing or unreadable: $secret_file" >&2
    exit 2
  fi
  awk 'length($0) > 0' "$secret_file" >> "$patterns"
done
if ! test -s "$patterns"; then
  echo "the secret-value set is empty (no non-empty line in: $*); refusing a deep scan that would report a tree it never searched as clean" >&2
  exit 2
fi

found=""
failed_archives=()
archive_hits=0
archive_index=0
while IFS= read -r -d '' archive; do
  archive_index=$((archive_index + 1))
  dest="$work/unpacked-${archive_index}-$(echo "$archive" | sed 's#/#_#g')"
  scan_log="$work/archive-scan-${archive_index}.log"
  mkdir -p "$dest"
  if unzip -qq -o "$archive" -d "$dest" 2>"$work/archive-unzip-${archive_index}.log"; then
    scan_status=0
    bash scripts/check-sensitive-evidence.sh "$dest" "$@" > /dev/null 2> "$scan_log" || scan_status=$?
    case "$scan_status" in
      0)
        ;;
      1)
        echo "sensitive value found inside archive: $archive" >&2
        # The unpacked tree is scratch; each hit line is re-pointed at the
        # archive the member came from so the report stays actionable.
        while IFS= read -r hit_line; do
          rest="${hit_line#hit: }"
          rest="${rest#"$dest"}"
          rest="${rest#/}"
          printf 'hit: %s!%s\n' "$archive" "$rest" >&2
        done < <(grep '^hit: ' "$scan_log" || true)
        hits_here="$(grep -c '^hit: ' "$scan_log" 2>/dev/null || true)"
        archive_hits=$((archive_hits + ${hits_here:-0}))
        found=1
        ;;
      *)
        echo "scan of unpacked archive failed (exit status $scan_status): $archive" >&2
        sed 's/^/  /' "$scan_log" >&2 || true
        failed_archives+=("$archive")
        ;;
    esac
  else
    echo "could not unpack: $archive" >&2
    sed 's/^/  unzip: /' "$work/archive-unzip-${archive_index}.log" >&2 || true
    failed_archives+=("$archive")
  fi
done < <(find "$evidence" -type f -name '*.zip' -print0 | LC_ALL=C sort -z)

# Loose files: their exit code is authoritative for the loose part of the tree.
# The base scanner's per-file hit lines already carry the real paths here.
loose_status=0
bash scripts/check-sensitive-evidence.sh "$evidence" "$@" || loose_status=$?

overall="$loose_status"
if [[ -n "$found" ]]; then
  overall=1
fi
if (( ${#failed_archives[@]} > 0 )); then
  echo "deep scan failed: the following archives could not be unpacked or scanned:" >&2
  printf '  %s\n' "${failed_archives[@]}" >&2
  if [[ "$overall" == "0" ]]; then
    overall=3
  fi
fi

if [[ "$overall" == "1" ]]; then
  echo "deep scan hit: ${archive_hits} hit(s) inside ${archive_index} archive(s) plus the loose-file report above" >&2
  exit 1
fi
if [[ "$overall" != "0" ]]; then
  exit "$overall"
fi
echo "deep scan clean (loose files + $(find "$evidence" -type f -name '*.zip' | wc -l) zip archives)"
